"""Dynamic Prompts escaping: keep LLM-invented variant syntax out of the
final prompt.

Host-independent (stdlib only). This extension runs AFTER
sd-dynamic-prompts (metadata.ini orders the callback after DP's), so the
prompt it receives is already expanded and nothing expands tokens again
after it - any DP variant syntax ({red|blue}) the LLM invents on its own
would reach the model verbatim. Those pipes are escaped to commas before
write-back. Tokens already present in the prompt the LLM received (which
may include unexpanded DP syntax the user intentionally left in place),
and variants containing wildcard tokens, are always kept as-is.

Separators are passed explicitly - the entry reads them from the DP
settings - so this module is testable outside the WebUI host.
"""

from __future__ import annotations

DEFAULT_VARIANT_START = "{"
DEFAULT_VARIANT_END = "}"
DEFAULT_WILDCARD_WRAP = "__"


def contains_wildcard(text: str, wc_wrap: str) -> bool:
    """Check if text contains a wildcard token (wc_wrap + name + wc_wrap)."""
    if not wc_wrap:
        return False
    # Look for pattern: wc_wrap ... wc_wrap where there's at least one char between
    wc_len = len(wc_wrap)
    if wc_len * 2 + 1 > len(text):
        return False
    first = text.find(wc_wrap)
    if first < 0:
        return False
    second = text.find(wc_wrap, first + wc_len)
    return second > first + wc_len  # At least one char between the wraps


def find_matching_variant_end(text: str, start: int, v_start: str, v_end: str) -> int | None:
    """Find the position of the matching variant_end, accounting for nesting.

    Returns the index of the first character of variant_end, or None if not found.

    When v_start == v_end (e.g. both are '###'), we check v_end FIRST so the
    closing token is matched before the opening token, keeping depth correct.
    """
    same_delim = v_start == v_end
    depth = 1
    i = start
    limit = len(text) - len(v_end)
    while i <= limit:
        if same_delim:
            # When delimiters are identical, check end first so we close before opening
            if text[i:i + len(v_end)] == v_end:
                depth -= 1
                if depth == 0:
                    return i
                i += len(v_end)
                continue
            # Also acts as start (nesting)
            if text[i:i + len(v_start)] == v_start:
                depth += 1
                i += len(v_start)
                continue
        else:
            if text[i:i + len(v_start)] == v_start:
                depth += 1
                i += len(v_start)
                continue
            if text[i:i + len(v_end)] == v_end:
                depth -= 1
                if depth == 0:
                    return i
                i += len(v_end)
                continue
        i += 1
    return None


def extract_variant_blocks(text: str, v_start: str, v_end: str, out: set[str]) -> None:
    """Extract all variant blocks from text and add them to the out set."""
    i = 0
    while i < len(text):
        if text[i:i + len(v_start)] == v_start:
            end_pos = find_matching_variant_end(text, i + len(v_start), v_start, v_end)
            if end_pos is not None:
                full_block = text[i:end_pos + len(v_end)]
                out.add(full_block)
                i = end_pos + len(v_end)
                continue
        i += 1


def _escape_variant_block(
    full_block: str,
    inner: str,
    original_variants: set[str],
    v_start: str,
    v_end: str,
    wc_wrap: str,
) -> str:
    """Escaped form of one variant block: kept as-is when intentional
    (contains wildcard syntax the LLM was told to preserve, or appears
    verbatim in the original prompt), otherwise pipes become commas."""
    if contains_wildcard(inner, wc_wrap) or full_block in original_variants:
        return full_block
    return f"{v_start}{inner.replace('|', ',')}{v_end}"


def escape_accidental_dp_syntax(
    original: str,
    enhanced: str,
    *,
    v_start: str = DEFAULT_VARIANT_START,
    v_end: str = DEFAULT_VARIANT_END,
    wc_wrap: str = DEFAULT_WILDCARD_WRAP,
) -> str:
    """Escape variant pipes the LLM invented that weren't in the input.

    DP variant syntax (e.g. {red|blue}) newly generated by the LLM is
    never expanded after this point, so those pipes are replaced with
    commas to keep the final prompt clean. Intentional variant blocks
    (containing wildcards, or present verbatim in the input) are kept
    as-is. Separators are explicit parameters so the function is testable
    without the host.
    """
    # Collect all original variant blocks for comparison
    original_variants: set[str] = set()
    extract_variant_blocks(original, v_start, v_end, original_variants)

    result: list[str] = []
    i = 0
    while i < len(enhanced):
        # Check for variant start at position i
        if enhanced[i:i + len(v_start)] == v_start:
            # Find the matching end (handles nested variants)
            end_pos = find_matching_variant_end(enhanced, i + len(v_start), v_start, v_end)
            if end_pos is not None:
                full_block = enhanced[i:end_pos + len(v_end)]
                inner = full_block[len(v_start):-len(v_end)]
                result.append(_escape_variant_block(full_block, inner, original_variants, v_start, v_end, wc_wrap))
                i = end_pos + len(v_end)
                continue

        result.append(enhanced[i])
        i += 1

    return "".join(result)
